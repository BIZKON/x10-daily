/**
 * Привязка партнёра к его версии коммерческого предложения (`/kp/<slug>/`).
 *
 * 🔴 Слаг связывает человека с документом, который уже разослан клиентам. Если
 * он привяжется не к тому, партнёр начнёт рекомендовать чужую страницу с чужими
 * контактами, и лид уйдёт мимо него. Поэтому здесь нет догадок: либо точное
 * совпадение по имени в Telegram, либо владелец ставит слаг руками.
 */

/** Потолок длины — как у колонки `partners.slug`. */
const MAX_SLUG = 64;

/**
 * Приводит слаг к виду, пригодному для адреса.
 *
 * 🔴 Кириллица не проходит намеренно. Адрес `/kp/иванов/` выглядит рабочим, но
 * в мессенджере превращается в процентное кодирование, а партнёр отправит его
 * клиенту как есть и получит ссылку, которая читается как ошибка.
 *
 * `null` — это не сбой, а осознанное «страницы нет»: у партнёра может не быть
 * своей версии КП, и кабинет просто не покажет блок со ссылкой.
 */
export function normalizeSlug(raw: string | null | undefined): string | null {
  if (!raw) return null;
  const s = String(raw)
    .trim()
    .toLowerCase()
    .replace(/\s+/g, "-")
    .replace(/[^a-z0-9-]/g, "")
    .replace(/-{2,}/g, "-")
    .replace(/^-|-$/g, "");
  if (!s) return null;
  // Обрезаем, а не отвергаем: длинный слаг — это опечатка владельца, ронять из-за
  // неё сохранение всей карточки незачем.
  return s.slice(0, MAX_SLUG);
}

/**
 * Слаг, забронированный за именем в Telegram.
 *
 * Партнёрские версии КП напечатаны и разосланы ДО того, как человек впервые
 * открыл приложение. Бронь позволяет привязать страницу в момент регистрации,
 * а не гоняться за владельцем с просьбой проставить слаг руками.
 *
 * Формат настройки: `username:slug` через запятую. Сломанные пары молча
 * пропускаются — из-за опечатки в одной не должны отвалиться остальные.
 */
export function reservedSlugFor(
  reservations: string | null | undefined,
  username: string | null | undefined,
): string | null {
  if (!reservations || !username) return null;
  const want = String(username).trim().replace(/^@/, "").toLowerCase();
  if (!want) return null;

  for (const pair of String(reservations).split(",")) {
    const [name, slug] = pair.split(":");
    if (!name || !slug) continue;
    if (name.trim().replace(/^@/, "").toLowerCase() === want) {
      return normalizeSlug(slug);
    }
  }
  return null;
}
