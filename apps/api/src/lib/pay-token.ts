import { randomBytes } from "node:crypto";

/**
 * Код ссылки на оплату (спека 7).
 *
 * Ссылка живёт в чужой переписке: партнёр отправляет её клиенту в Telegram,
 * клиент пересылает бухгалтеру, бухгалтер открывает с рабочего компьютера.
 * Отсюда три требования:
 *
 * 1. **Не угадывается.** Токен — единственная защита заказа: страница
 *    публичная, входа по Telegram у клиента нет. 96 бит случайности.
 * 2. **Переносится текстом.** Только латиница, цифры и дефис с подчёркиванием:
 *    кириллица в адресе превращается в процентное кодирование, а такую ссылку
 *    человек отправит клиенту как есть — и она сломается.
 * 3. **Не несёт смысла.** Ни номера заказа, ни партнёра: по ссылке нельзя
 *    подобрать соседний заказ и нельзя понять, кто и сколько заработал.
 */

/** Длина в символах: 12 случайных байт в base64url дают ровно 16. */
export const PAY_TOKEN_LENGTH = 16;

export function generatePayToken(): string {
  return randomBytes(12).toString("base64url");
}

/** Похоже ли это на наш токен — до похода в базу. */
export function isPayToken(value: string): boolean {
  return value.length === PAY_TOKEN_LENGTH && /^[A-Za-z0-9_-]+$/.test(value);
}
