import { describe, expect, it } from "vitest";
import { amountInWords } from "../src/lib/amount-in-words";

/**
 * Сумма прописью в счёте (спека 7).
 *
 * Реквизит обязательный: бухгалтерия сверяет цифру с прописью и при
 * расхождении возвращает счёт. Ошибка склонения здесь не падает — она делает
 * документ, над которым посмеются, и это на 350 000 ₽.
 */

describe("рубли и склонения", () => {
  it("наши прайсовые суммы", () => {
    expect(amountInWords(350_000)).toBe("Триста пятьдесят тысяч рублей 00 копеек");
    expect(amountInWords(180_000)).toBe("Сто восемьдесят тысяч рублей 00 копеек");
    expect(amountInWords(175_000)).toBe("Сто семьдесят пять тысяч рублей 00 копеек");
  });

  it("🔴 тысячи — женского рода", () => {
    // «Один тысяча» и «два тысячи» — классическая ошибка самописных функций.
    expect(amountInWords(1_000)).toBe("Одна тысяча рублей 00 копеек");
    expect(amountInWords(2_000)).toBe("Две тысячи рублей 00 копеек");
    expect(amountInWords(21_000)).toBe("Двадцать одна тысяча рублей 00 копеек");
    expect(amountInWords(22_000)).toBe("Двадцать две тысячи рублей 00 копеек");
    expect(amountInWords(5_000)).toBe("Пять тысяч рублей 00 копеек");
  });

  it("рубль, рубля, рублей", () => {
    expect(amountInWords(1)).toBe("Один рубль 00 копеек");
    expect(amountInWords(2)).toBe("Два рубля 00 копеек");
    expect(amountInWords(5)).toBe("Пять рублей 00 копеек");
    expect(amountInWords(11)).toBe("Одиннадцать рублей 00 копеек");
    expect(amountInWords(21)).toBe("Двадцать один рубль 00 копеек");
    expect(amountInWords(112)).toBe("Сто двенадцать рублей 00 копеек");
  });

  it("одиннадцать–девятнадцать не путаются с единицами", () => {
    // 12 000 — «двенадцать тысяч», а не «двенадцать тысяча».
    expect(amountInWords(12_000)).toBe("Двенадцать тысяч рублей 00 копеек");
    expect(amountInWords(111)).toBe("Сто одиннадцать рублей 00 копеек");
  });

  it("копейки", () => {
    expect(amountInWords(10.5)).toBe("Десять рублей 50 копеек");
    expect(amountInWords(0.01)).toBe("Ноль рублей 01 копейка");
    expect(amountInWords(1234.56)).toBe(
      "Одна тысяча двести тридцать четыре рубля 56 копеек",
    );
  });

  it("ноль — тоже сумма", () => {
    expect(amountInWords(0)).toBe("Ноль рублей 00 копеек");
  });

  it("миллионы", () => {
    expect(amountInWords(1_000_000)).toBe("Один миллион рублей 00 копеек");
    expect(amountInWords(2_500_000)).toBe("Два миллиона пятьсот тысяч рублей 00 копеек");
    expect(amountInWords(5_000_000)).toBe("Пять миллионов рублей 00 копеек");
  });

  it("округляет до копейки, а не отбрасывает", () => {
    // 0.005 в меньшую сторону — это недостача в счёте.
    expect(amountInWords(10.005)).toBe("Десять рублей 01 копейка");
  });

  it("копейки склоняются", () => {
    expect(amountInWords(0.02)).toBe("Ноль рублей 02 копейки");
    expect(amountInWords(0.05)).toBe("Ноль рублей 05 копеек");
    expect(amountInWords(0.11)).toBe("Ноль рублей 11 копеек");
  });
});
