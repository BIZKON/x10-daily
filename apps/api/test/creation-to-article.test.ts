import { describe, expect, it } from "vitest";
import { toArticleDraft } from "../src/lib/creation-to-article";

/**
 * Превращение готового задания в статью.
 *
 * Ручной режим отдаёт плоский текст, а статья устроена блоками Smart Brevity.
 * Стык между ними — единственное место, где материал может потерять форму, и
 * потому он вынесен в чистую функцию: тут решается, что станет заголовком,
 * что вводкой, а что телом.
 */

const BODY = [
  "Ручная сверка актов забирает у бухгалтера часы в конце месяца.",
  "ИИ-агент сверяет позиции и собирает список расхождений.",
  "Бухгалтер проверяет только спорные строки.",
].join("\n\n");

describe("задание → статья", () => {
  it("заголовок становится тизером и адресом", () => {
    const d = toArticleDraft({ title: "Сверка склада за 20 минут", body: BODY });
    expect(d.tease).toBe("Сверка склада за 20 минут");
    expect(d.slug).toBe("sverka-sklada-za-20-minut");
  });

  it("🔴 первый абзац становится вводкой, остальные — телом", () => {
    // Иначе материал приедет в читалку одним куском без вводки, и лента,
    // которая показывает именно lede, останется пустой.
    const d = toArticleDraft({ title: "Заголовок", body: BODY });
    expect(d.lede).toBe("Ручная сверка актов забирает у бухгалтера часы в конце месяца.");
    expect(d.body).toEqual([
      { type: "paragraph", text: "ИИ-агент сверяет позиции и собирает список расхождений." },
      { type: "paragraph", text: "Бухгалтер проверяет только спорные строки." },
    ]);
  });

  it("материал из одного абзаца даёт вводку и пустое тело", () => {
    const d = toArticleDraft({ title: "Заголовок", body: "Одна мысль и всё." });
    expect(d.lede).toBe("Одна мысль и всё.");
    expect(d.body).toEqual([]);
  });

  it("🔴 лишние переводы строк не превращаются в пустые блоки", () => {
    // Пустой блок доезжает до читалки как дыра в вёрстке, и заметит её
    // читатель, а не мы.
    const d = toArticleDraft({ title: "З", body: "Первый.\n\n\n\n   \n\nВторой." });
    expect(d.body).toEqual([{ type: "paragraph", text: "Второй." }]);
  });

  it("одиночный перенос внутри абзаца не разрывает его", () => {
    const d = toArticleDraft({ title: "З", body: "Первый.\n\nВторая\nстрока." });
    expect(d.body).toEqual([{ type: "paragraph", text: "Вторая\nстрока." }]);
  });

  it("считает слова по всему материалу, а не по одному абзацу", () => {
    const d = toArticleDraft({ title: "Заголовок", body: BODY });
    // 10 + 7 + 5 по трём абзацам. Заголовок в счёт не входит: читают материал.
    expect(d.wordCount).toBe(22);
  });

  it("время чтения не опускается ниже 20 секунд", () => {
    // Ноль секунд в карточке читается как поломка.
    const d = toArticleDraft({ title: "З", body: "Коротко." });
    expect(d.readSeconds).toBeGreaterThanOrEqual(20);
  });

  it("заголовок с одними символами всё равно даёт непустой адрес", () => {
    // Пустой slug сделал бы статью недоступной по ссылке.
    const d = toArticleDraft({ title: "!!! ???", body: "Текст." });
    expect(d.slug.length).toBeGreaterThan(0);
  });
});
