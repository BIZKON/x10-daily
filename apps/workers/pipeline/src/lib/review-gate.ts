/**
 * Ворота ревью (Спека 4): что из очереди канала можно публиковать.
 *
 * 🔴 Почему решение вынесено сюда из SQL. Прежние ворота были условием в
 * запросе — «не публиковать, пока есть карточка в состоянии awaiting». Условие
 * читалось как строгое, но по смыслу было противоположным: отсутствие карточки
 * означало разрешение. А карточка рождается лишь побочным эффектом успешной
 * генерации обложки и не появляется, когда фича выключена, кончился баланс,
 * картинка уже была или обложка просто не успела к слоту.
 *
 * Замер на проде 10.08.2026: за три дня 6 постов из 20 ушли в канал вообще без
 * карточки, за неделю — 26 из 41. То есть предохранителя не было.
 *
 * Правило теперь одно: **материал выходит в канал, только если решение по нему
 * принято, либо истёк предохранитель**. Ворота по умолчанию закрыты.
 */

export type QueueCandidate = {
  articleId: string;
  /** Когда материал встал в очередь канала. */
  queuedAt: Date;
  /** Момент создания карточки, которая ЖДЁТ решения. `null` — такой нет. */
  awaitingSince: Date | null;
  /** Есть ли по материалу хоть какая-то карточка: решение уже принимали. */
  hasAnyCard: boolean;
};

export type GateOptions = {
  /** Группа «Редакция» настроена. Нет — ворот нет, экземпляр работает как раньше. */
  reviewConfigured: boolean;
  /**
   * Предохранитель в часах. `0` — выключен, ворота жёсткие.
   *
   * Он важнее строгости: день без редактора не должен превращаться в день
   * тишины в канале, а медиа так себе позволить не может.
   */
  gateHours: number;
  now: Date;
};

function waitedLongEnough(since: Date, o: GateOptions): boolean {
  if (o.gateHours <= 0) return false;
  return o.now.getTime() - since.getTime() >= o.gateHours * 3_600_000;
}

/** Пропускают ли ворота именно этот материал. */
export function mayPost(row: QueueCandidate, o: GateOptions): boolean {
  if (!o.reviewConfigured) return true;

  // Карточка ждёт решения — держим до истечения предохранителя.
  if (row.awaitingSince) return waitedLongEnough(row.awaitingSince, o);

  // 🔴 Карточки нет вовсе. Раньше это читалось как разрешение; теперь —
  // как «решение ещё не принимали», и материал ждёт наравне с остальными.
  if (!row.hasAnyCard) return waitedLongEnough(row.queuedAt, o);

  // Карточка есть и решения не ждёт: редактор высказался.
  return true;
}

/**
 * Первый материал очереди, который ворота выпускают.
 *
 * Порядок остаётся FIFO, но заблокированная голова НЕ держит остальных: одна
 * статья на ревью не должна означать пустой слот — это ровно тот случай, когда
 * канал молчит без причины.
 */
export function pickPostable(rows: readonly QueueCandidate[], o: GateOptions): string | null {
  for (const row of rows) {
    if (mayPost(row, o)) return row.articleId;
  }
  return null;
}

/** Строка очереди: материал плюс формат, которым он выходит (миграция 0033). */
export type QueueRow = QueueCandidate & { format: string };

/**
 * Первая строка очереди, которую ворота выпускают, — вместе с её форматом.
 *
 * 🔴 Слот забирает ОДНУ строку, а не весь материал. С появлением форматов у
 * материала стало несколько строк на одну площадку, и «опубликовать материал»
 * означало бы четыре публикации подряд — решение владельца 13.08: по одному
 * формату в слот, материал живёт день разными гранями.
 *
 * Порядок FIFO сохраняется, и заблокированная голова по-прежнему не держит
 * остальных: одна статья на ревью не должна означать пустой слот.
 */
export function pickPostableRow(
  rows: readonly QueueRow[],
  o: GateOptions,
): { articleId: string; format: string } | null {
  for (const row of rows) {
    if (mayPost(row, o)) return { articleId: row.articleId, format: row.format };
  }
  return null;
}
