import { z } from "zod";
import { defineAgent } from "../define-agent";
import { INGEST_CATEGORIES, INGEST_TEMPLATES } from "./ingest";

/**
 * BreakdownAgent — второй вход конвейера (план 09.08.2026, пункт 1).
 *
 * Первый вход — ленты источников: система сама находит темы. Второй — человек
 * даёт ссылку на удачный чужой материал и получает СВОЙ, в своей рубрике и
 * своим голосом.
 *
 * 🔴 Агент делает ДВЕ вещи сразу, и это осознанно:
 *  1. Раскладывает исходник по каркасу «хук → доказательство → арка → призыв».
 *     Каркас не украшение: именно он объясняет, ПОЧЕМУ материал сработал, и
 *     переносится на другую тему, тогда как сам текст — нет.
 *  2. Собирает тему в том же виде, в каком её отдаёт гейт лент, — чтобы
 *     дальше работал существующий конвейер, а не вторая труба рядом.
 *
 * ⚠️ Это НЕ переписывание чужого текста. На выходе тема и угол, а дальше пишет
 * DraftAgent с нашим голосом и чёрным списком. Копировать чужой материал —
 * и юридический риск, и провал по смыслу: у клиента другая аудитория.
 */

const inputSchema = z.object({
  /** Адрес исходника — агент учитывает вес и тип издания. */
  url: z.string(),
  /** Заголовок страницы, если удалось достать. */
  title: z.string(),
  /** Извлечённый текст страницы. */
  text: z.string(),
  /** Чем занимается клиент — чтобы адаптация была под его бизнес, а не общая. */
  clientContext: z.string().optional(),
});

/** Одна ступень каркаса: чем она была в исходнике и как переносится к нам. */
const beatSchema = z.object({
  /** Что именно сделано в исходнике. Коротко, по факту. */
  source: z.string().min(1),
  /** Как это же работает на материале клиента. */
  adapted: z.string().min(1),
});

const outputSchema = z.object({
  /**
   * Годится ли исходник вообще. Реклама, пустая страница, текст не по делу —
   * честный отказ лучше выдуманной темы.
   */
  usable: z.boolean(),
  /** Почему не годится. Заполняется только при usable=false. */
  rejectReason: z.string().optional(),

  /** Разбор по каркасу — то, что увидит редактор. */
  hook: beatSchema,
  proof: beatSchema,
  arc: beatSchema,
  cta: beatSchema,
  /** Одной фразой: за счёт чего материал сработал. */
  whyItWorked: z.string().min(1),

  /* --- дальше поля для конвейера, форма как у гейта лент --- */
  topic: z.string().min(1),
  context: z.string().min(1),
  category: z.enum(INGEST_CATEGORIES).nullable().catch(null),
  subcategory: z.string().nullable().catch(null),
  template: z.enum(INGEST_TEMPLATES).nullable().catch(null),
  tags: z.array(z.string()).max(6).default([]),
  political: z.boolean().default(false),
});

const SYSTEM = `Ты — редактор-аналитик ProAgent AI. Тебе дают чужой материал по ссылке.

ТВОЯ ЗАДАЧА — не пересказать его, а понять, ПОЧЕМУ он сработал, и перенести приём на материал нашего клиента.

РАЗБЕРИ ИСХОДНИК ПО ЧЕТЫРЁМ СТУПЕНЯМ:
- hook — чем он захватывает внимание в первые секунды;
- proof — чем подкрепляет: цифры, факты, имена, случай;
- arc — как развивается: от чего к чему ведёт читателя;
- cta — к какому действию подводит в конце.

Для каждой ступени скажи ДВЕ вещи: что сделано в исходнике (source) и как то же самое сработает на теме клиента (adapted).

ЗАТЕМ СОБЕРИ ТЕМУ для нашего конвейера:
- topic — о чём будет НАШ материал. Не заголовок исходника, а наша тема под тем же приёмом.
- context — фактура для автора: что известно, какие цифры, откуда. Сюда же положи, какой приём переносим.
- category — одна из: news (новости ИИ), cases (кейсы внедрения), howto (обучение), tools (инструменты), business (практика), founder (от основателя).
- template — card-news (короткая новость), deep-dive (разбор), daily-take (мнение основателя), guide (инструкция).
- tags — до шести коротких тегов.
- political — true, если тема затрагивает политику, регулирование или требует проверки фактов из нескольких источников.

ЖЁСТКИЕ ПРАВИЛА:
1. НЕ копируй текст исходника. Ни абзацами, ни фразами. Мы берём приём, а не слова.
2. НЕ выдумывай цифры и цитаты. Если в исходнике нет числа — его нет и у нас.
3. Угол всегда один: практическая выгода для бизнеса — часы, деньги, конверсия. Не «интересная новость», а «что это даёт».
4. Никакого хайпа: без «революционный», «прорывной», «магия нейросетей», «уникальный».
5. Если исходник — реклама, пустая страница, набор ссылок или текст не по делу: usable=false и объясни причину человеческим языком. Выдуманная тема хуже отказа.
6. Отвечай ТОЛЬКО по-русски.`;

function formatBreakdownInput(input: z.infer<typeof inputSchema>): string {
  const parts = [
    `ССЫЛКА: ${input.url}`,
    input.title ? `ЗАГОЛОВОК: ${input.title}` : "",
    input.clientContext ? `ЧЕМ ЗАНИМАЕТСЯ КЛИЕНТ: ${input.clientContext}` : "",
    "",
    "ТЕКСТ ИСХОДНИКА:",
    input.text,
  ];
  return parts.filter(Boolean).join("\n");
}

export const BreakdownAgent = defineAgent({
  name: "breakdown",
  tier: "SONNET",
  system: SYSTEM,
  inputSchema,
  outputSchema,
  formatInput: formatBreakdownInput,
  maxOutputTokens: 2048,
});

export type BreakdownInput = z.infer<typeof inputSchema>;
export type BreakdownOutput = z.infer<typeof outputSchema>;
