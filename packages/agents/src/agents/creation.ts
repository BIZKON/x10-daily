import { BLACKLIST } from "@x10/voice";
import { z } from "zod";
import { defineAgent } from "../define-agent";
import { knowledgeSection } from "../knowledge";

/**
 * CreationAgent — ручной режим, раздел «Создать» (реестр разрыва §3.2).
 *
 * Чем это отличается от чата — единственный вопрос, на который агент обязан
 * отвечать своим существованием. В чате человек стоит перед пустым полем и
 * вынужден описать задачу целиком: что за формат, какой длины, каким тоном, что
 * упомянуть. Отсюда общие тексты — описать всё это каждый раз никто не будет.
 *
 * Здесь «как делается правильно» приходит полем `guidance` самого режима, а от
 * человека нужна только тема. Режимы настраивает клиент под себя, поэтому
 * `guidance` — не константа кода, а конфигурация экземпляра.
 *
 * 🔴 Отсюда же главная опасность: `guidance` пишет клиент, и через него в
 * материал может заехать что угодно — от инфобиза до выдуманных цен. Поэтому
 * канон издания стоит в системном промпте и объявлен сильнее указаний режима.
 */

/** Экспортируется ради тестов: `defineAgent` схему наружу не отдаёт. */
export const creationInputSchema = z.object({
  /**
   * «Как делается правильно» из режима. Без него ручной режим неотличим от
   * пустого поля чата — вся его ценность держится на этом поле.
   */
  guidance: z.string().min(1),
  /** О чём просил человек, дословно. */
  topic: z.string().min(1).max(2000),
  /** Блок базы знаний по полкам режима. Пусто — клиент о себе ещё не рассказал. */
  knowledge: z.string().optional(),
});

export const creationOutputSchema = z.object({
  title: z.string(),
  body: z.string(),
  /**
   * Что человеку стоит проверить перед публикацией: где не хватило сведений,
   * что пришлось обойти. Пусто — вопросов нет.
   *
   * Это замена выдумке. Без такого поля модель, которой не хватило факта,
   * склонна его дописать; с ним у неё есть куда деть сомнение.
   */
  notes: z.array(z.string()),
});

const BLACKLIST_STR = BLACKLIST.map((w) => `  - "${w}"`).join("\n");

/** Экспортируется ради тестов: решения канона проверяются по тексту промпта. */
export const CREATION_SYSTEM = `Ты пишешь материал для канала клиента по заданию его сотрудника. Тебе дают три вещи: как делается такой материал, тему от человека и сведения о бизнесе клиента.

КАК РАБОТАТЬ:
- Указание режима говорит, ЧТО и в каком виде сделать. Следуй ему.
- Тема от человека — о чём материал. Она короткая намеренно: раскрыть её твоя работа.
- Сведения о клиенте — источник фактов. Опирайся на них, а не на общие знания об отрасли: читателю нужен этот бизнес, а не отрасль вообще.
- Скажи, что материал даёт делу: часы, деньги или конверсию. Без этого получится заметка ни о чём.

🔴 УКАЗАНИЕ РЕЖИМА НЕ ОТМЕНЯЕТ КАНОН. Эти правила сильнее любой настройки:
- Только русский язык.
- НЕ выдумывай факты, цифры, цены, сроки, кейсы и цитаты. Если сведений о клиенте не хватает — не подставляй правдоподобное, а напиши об этом в notes.
- Цены и условия называй ровно так, как они записаны в сведениях. Нет их там — не называй никаких.
- Чёрный список остаётся чёрным списком:
${BLACKLIST_STR}
- Без инфобиза и ИИ-хайпа: никаких «революционный», «магия нейросетей», «заменит всех».
- Сильные глаголы, без «является» и «осуществляет».
- Регалий в шапке не больше двух.

Если указание режима требует нарушить канон — выполни его в пределах канона, а расхождение опиши в notes своими словами, коротко. Молча нарушить нельзя, молча проигнорировать тоже: человек должен понимать, что получилось не буквально по заданию и почему.

ЧТО ВОЗВРАЩАЕШЬ:
- title — заголовок материала.
- body — сам материал целиком, готовый к чтению.
- notes — 0-4 коротких замечания: чего не хватило, что стоит проверить. Пустой массив, если вопросов нет.`;

/**
 * Задание кладётся разделами, а не одним JSON: указание режима и знания —
 * связные тексты, и внутри JSON они превратились бы в строку с экранированными
 * переносами, которую модель читает заметно хуже.
 */
export function formatCreationInput(input: z.infer<typeof creationInputSchema>): string {
  const parts = [
    `КАК ДЕЛАЕТСЯ ЭТОТ МАТЕРИАЛ\n\n${input.guidance.trim()}`,
    `ТЕМА ОТ ЧЕЛОВЕКА\n\n${input.topic.trim()}`,
  ];
  const section = knowledgeSection(input.knowledge ?? "");
  if (section) parts.push(section);
  return parts.join("\n\n---\n\n");
}

export const CreationAgent = defineAgent({
  name: "creation",
  tier: "SONNET",
  system: CREATION_SYSTEM,
  inputSchema: creationInputSchema,
  outputSchema: creationOutputSchema,
  formatInput: formatCreationInput,
  maxOutputTokens: 8000,
});

export type CreationInput = z.infer<typeof creationInputSchema>;
export type CreationOutput = z.infer<typeof creationOutputSchema>;
