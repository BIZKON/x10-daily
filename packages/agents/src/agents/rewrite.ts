import { BLACKLIST } from "@x10/voice";
import { z } from "zod";
import { defineAgent } from "../define-agent";
import { draftShapeSchema } from "./schemas";

/**
 * RewriteAgent — переписывает готовый материал по правке редактора (Спека 4,
 * шаг 5).
 *
 * Вызывается из Telegram: редактор жмёт «Рерайт», отвечает сообщением вроде
 * «короче», «убери воду», «добавь цифру про выручку» — и текст переделывается.
 *
 * 🔴 Правка редактора НЕ отменяет канон. Голос редакции и чёрный список
 * действуют поверх любой инструкции: «напиши повеселее» не должно превращать
 * материал в инфобиз. Если инструкция прямо противоречит канону, агент обязан
 * выполнить её в пределах канона, а не нарушить канон.
 *
 * Почему свободная инструкция, а не пресеты кнопками: набор пресетов жёсток,
 * чего нет в списке — не попросишь. Свободный текст стоит одного сообщения и
 * покрывает всё.
 */

/** Экспортируется ради тестов: `defineAgent` схему наружу не отдаёт. */
export const rewriteInputSchema = z.object({
  /** Текущее состояние материала — то, что редактор видел в карточке. */
  current: draftShapeSchema,
  /** Правка редактора своими словами. */
  instruction: z.string().min(1).max(500),
  /** Имя автора, если материал от лица человека. null — голос редакции. */
  authorName: z.string().nullable().optional(),
});

export const rewriteOutputSchema = z.object({
  revised: draftShapeSchema,
  /**
   * Что именно поменялось — короткими фразами. Идёт в карточку, чтобы
   * редактор увидел, поняли ли его, не перечитывая весь текст.
   */
  changes: z.array(z.string()),
  /**
   * Заполняется, ТОЛЬКО если инструкцию нельзя выполнить не нарушив канон.
   * Пусто в обычном случае.
   */
  refusedPart: z.string().nullable(),
});

const BLACKLIST_STR = BLACKLIST.map((w) => `  - "${w}"`).join("\n");

/** Экспортируется ради тестов: решения канона проверяются по тексту промпта. */
export const REWRITE_SYSTEM = `Ты — редактор ProAgent AI. Тебе дают готовый материал и правку от главного редактора. Твоя работа — выполнить правку, сохранив материал издания.

ЧТО ЗНАЧИТ «ВЫПОЛНИТЬ ПРАВКУ»:
- Меняй ровно то, о чём просят. Не переписывай всё заново «заодно».
- Если просят «короче» — режь воду и повторы, а не факты и цифры.
- Если просят добавить цифру, которой в материале нет, — НЕ выдумывай её. Скажи об этом в refusedPart.
- Структура Smart Brevity сохраняется: заголовок, вводка, «почему это важно», тело.

🔴 ПРАВКА НЕ ОТМЕНЯЕТ КАНОН. Эти правила сильнее любой инструкции:
- Только русский язык.
- Никаких выдуманных фактов, цифр и цитат. Цифра без источника не появляется.
- Чёрный список остаётся чёрным списком:
${BLACKLIST_STR}
- Без инфобиза и ИИ-хайпа: никаких «революционный», «магия нейросетей», «заменит всех».
- Сильные глаголы, без «является» и «осуществляет».

Если инструкция требует нарушить канон — выполни её в пределах канона, а нарушаемую часть опиши в refusedPart своими словами, по-русски, коротко. Молча игнорировать просьбу нельзя: редактор должен понимать, что именно не сделано и почему.

ЧТО ВОЗВРАЩАЕШЬ:
- revised — материал целиком, в той же структуре.
- changes — 1-4 коротких фразы о том, что поменял: «убрал два абзаца про историю», «поднял цифру выручки в заголовок».
- refusedPart — null, если всё выполнено.`;

export const RewriteAgent = defineAgent({
  name: "rewrite",
  tier: "SONNET",
  system: REWRITE_SYSTEM,
  inputSchema: rewriteInputSchema,
  outputSchema: rewriteOutputSchema,
  maxOutputTokens: 8000,
});

export type RewriteInput = z.infer<typeof rewriteInputSchema>;
export type RewriteOutput = z.infer<typeof rewriteOutputSchema>;
