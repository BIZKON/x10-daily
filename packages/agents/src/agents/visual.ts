import { z } from "zod";
import { defineAgent } from "../define-agent";

/**
 * VisualAgent — готовит ЦЕЛЬНУЮ обложку-постер для Nano Banana 2.
 *
 * Канон: `packages/voice/visual.md`.
 *
 * ⚠️ АРХИТЕКТУРА ИЗМЕНЕНА в сессии 30 (замер, а не теория). Раньше считалось, что
 * модель коверкает кириллицу, поэтому текст накладывали поверх картинки. Проверка
 * на живом шлюзе показала обратное: Nano Banana 2 рисует русский текст чисто,
 * включая брендовый знак и кнопку, и кадр получается ЦЕЛЬНЫМ — текст живёт внутри
 * композиции, а не лежит наклейкой сверху. Слой наложения удалён.
 *
 * Агент отдаёт три поля: короткий заголовок, подзаголовок и сцену. Промпт для
 * image-модели собирает `buildPosterPrompt`.
 */

/**
 * Лимиты текста в кадре. Исследование обложек: 3-5 слов в заголовке, иначе он не
 * читается в ленте на телефоне. Длинный `tease` статьи для кадра не годится —
 * его сжимает агент.
 */
export const HEADLINE_MAX = 26;
export const SUB_MAX = 42;

/** Подпись рубрики (кикер) в кадре. */
export const KICKER: Record<string, string> = {
  news: "НОВОСТИ ИИ",
  cases: "КЕЙС",
  howto: "ОБУЧЕНИЕ",
  tools: "ИНСТРУМЕНТЫ",
  business: "ПРАКТИКА",
  founder: "ОТ ОСНОВАТЕЛЯ",
};

/**
 * Рекламная строка чередуется по рубрике (решение владельца): кейсы и практика
 * ведут на лид, остальное — в контент.
 */
export function ctaFor(category: string): string {
  return category === "cases" || category === "business"
    ? "Обсудить внедрение"
    : "Разбор в Mini App";
}

/** Регистр столпа под рубрику (visual.md §«Привязка к столпам»). */
const PILLARS = {
  news: "сдержанная концептуальная иллюстрация инструмента или платформы как предмета",
  cases:
    "документальный индустриальный кадр реального делового контекста: производство, склад, подсобка ритейла, рабочее место в процессе",
  howto: "чистая плоская схема-предмет: обычный предмет как метафора одного шага метода",
  tools: "сдержанная концептуальная иллюстрация инструмента или платформы как предмета",
  business:
    "обобщённая фигура человека со спины или кадрированно, либо документальная абстракция денежного потока без признаков богатства",
  founder: "обобщённая фигура человека со спины, тихое рабочее место, лицо не видно",
} as const;

export const PILLAR_REGISTER: Record<string, string> = PILLARS;

const DEFAULT_PILLAR_KEY = "news";

/** Регистр столпа по рубрике; неизвестная рубрика → регистр `news`. */
export function pillarFor(category: string): string {
  return PILLAR_REGISTER[category] ?? PILLARS[DEFAULT_PILLAR_KEY];
}

/**
 * Запреты канона (visual.md §Off-limits) — словами, в конце промпта.
 *
 * ⚠️ БЕЗ слова «логотипы»: в кадре мы САМИ просим брендовый знак, и упоминание
 * логотипов рядом путает модель. Чужие бренды отсекаются формулировкой
 * «узнаваемые чужие марки».
 */
const FORBIDDEN =
  "ЗАПРЕЩЕНО: роскошь и богатство, золотые слитки, пачки денег, спорткары, яхты, часы, " +
  "стоковый успех (прыжки, кулак вверх, силуэт на рассвете), восходящие стрелки и графики как декор, " +
  "рукопожатия людей в костюмах, неон, киберпанк, свечение, мемные 3D-фигурки, огонь и драматургия, " +
  "лица реальных людей, узнаваемые чужие марки, флаги и политическая символика.";

/**
 * ⚠️ Цвета описаны СЛОВАМИ, без hex-кодов. Замер серии: модель однажды
 * напечатала «#D4A24C» прямо в кадре рядом со знаком — вытащила код из промпта
 * и отрисовала его как текст.
 */
const STYLE =
  "СТИЛЬ: редакционная деловая иллюстрация, сдержанный документальный тон, приглушённая палитра. " +
  "Фон тёмный, почти чёрный графитовый. Алый акцент дозированно, на малой части кадра. " +
  "Тонкая золотая линия как хром, никогда как богатство. Много воздуха, одна идея на кадр. " +
  "Спокойный ровный свет.";

const TYPO =
  "ТИПОГРАФИКА: плотный геометрический гротеск, белый текст, крупно и читаемо даже в мелком виде, " +
  "органично вписан в композицию, а не наклеен сверху.";

export type PosterInput = {
  headline: string;
  sub: string;
  scene: string;
  category: string;
};

/**
 * Собирает промпт цельной обложки.
 *
 * Порядок и формулировки выверены замерами на живом шлюзе:
 *  - надписи перечисляются БЕЗ кавычек вокруг них (иначе модель рисует кавычки);
 *  - брендовый знак описывается геометрией и текстом, без слова «логотип»;
 *  - hex-кодов нет вовсе (утекают в кадр как текст).
 */
export function buildPosterPrompt(a: PosterInput): string {
  const kicker = KICKER[a.category] ?? KICKER[DEFAULT_PILLAR_KEY];
  return [
    "Создай цельную горизонтальную обложку 16:9 для делового медиа об ИИ.",
    "",
    `СЦЕНА: ${a.scene.trim()}`,
    `Регистр сцены: ${pillarFor(a.category)}.`,
    "",
    "НАДПИСИ В КАДРЕ — воспроизвести ТОЧНО, по-русски, БЕЗ кавычек вокруг них, без лишних слов и без орфографических ошибок:",
    `надзаголовок мелко с разрядкой: ${kicker}`,
    `заголовок крупно: ${a.headline.trim()}`,
    `подзаголовок: ${a.sub.trim()}`,
    "",
    "В ЛЕВОМ НИЖНЕМ УГЛУ — небольшой красный квадрат со скруглёнными углами, внутри белые заглавные буквы PA, справа от него белая надпись ProAgent AI и золотая надпись мельче ИИ работает на вас.",
    "",
    `В ПРАВОМ НИЖНЕМ УГЛУ — тёмный прямоугольник с тонкой золотой рамкой и белой надписью внутри: ${ctaFor(a.category)}`,
    "",
    "КОМПОЗИЦИЯ: единый цельный кадр на всю площадь, без рамок по краям и без эффекта картинка-в-картинке.",
    "ВСЕ НАДПИСИ — СТРОГО В НИЖНЕЙ ТРЕТИ кадра, на спокойной тёмной области. В верхних двух третях — только предметная сцена, никакого текста.",
    // ⚠️ Зона под служебную плашку Mini App («Глубокий разбор», статус, рубрика).
    // Без резерва она ложится поверх заголовка постера и оба становятся
    // нечитаемыми — так и случилось на первой же живой публикации.
    "ВЕРХНИЙ ЛЕВЫЙ УГОЛ ОСТАВЬ ПУСТЫМ: примерно треть ширины и пятую часть высоты — ровная спокойная область без текста, без мелких деталей и без важных объектов. Туда приложение добавит свою подпись.",
    "",
    STYLE,
    "",
    TYPO,
    "",
    FORBIDDEN,
  ].join("\n");
}

const inputSchema = z.object({
  tease: z.string().min(1),
  lede: z.string().min(1),
  category: z.string().default(DEFAULT_PILLAR_KEY),
});

const outputSchema = z.object({
  /** Короткий заголовок В КАДР — 2-4 слова. Не `tease`: тот длинный и не влезет. */
  headline: z.string(),
  /** Подзаголовок в кадр — одна короткая фраза. */
  sub: z.string(),
  /** Описание сцены по-русски, 1-2 предложения. Только предметный ряд. */
  scene: z.string(),
});

const SYSTEM = `Ты — VisualAgent редакции ProAgent AI. По статье ты готовишь ТРИ вещи для обложки: короткий заголовок в кадр, подзаголовок и описание сцены.

КТО МЫ ВИЗУАЛЬНО:
Деловое редакционное медиа. Регистр — сдержанность Bloomberg / Axios / Stratechery плюс документальность. НЕ глянец, НЕ визуальный шум. Если кадр выглядит как обложка инфо-курса или мотивационный постер — это брак.

ЧТО ВОЗВРАЩАЕШЬ:

1. headline — заголовок В КАДР, не более ${HEADLINE_MAX} знаков, 2-4 слова.
   Это НЕ заголовок статьи: тот длинный. Сожми до сути, которая читается за секунду.
   Пример: «Сотни миллионов токенов за доллар» → «Токены подешевели».
   Пример: «ИИ-агент проверил 40 гипотез за ночь. Где скрыт главный риск?» → «40 гипотез за ночь».
   Цифру из статьи сохраняй, если она и есть суть.

2. sub — подзаголовок, не более ${SUB_MAX} знаков, одна короткая фраза.
   Добавляет смысл, а не повторяет заголовок.

3. scene — описание сцены по-русски, 1-2 предложения: что изображено (предметы, ракурс, композиция).
   Одна идея на кадр, много воздуха.

ЖЁСТКИЕ ПРАВИЛА ДЛЯ СЦЕНЫ:
- Только предметный ряд и обобщённые формы. Никаких названий компаний, людей и продуктов.
- Без лиц реальных людей. Человек — только со спины, силуэтом, кадрированно.
- Без роскоши, золотых слитков, денег пачками, спорткаров, яхт, часов.
- Без стокового успеха: прыжков, кулака вверх, силуэта на рассвете.
- Без восходящих стрелок и декоративных графиков вместо смысла.
- Без неона, киберпанка и свечения — это визуальный ИИ-хайп.
- Без мемных 3D-фигурок, огня, взрывов и драматургии.
- Без узнаваемых чужих марок, флагов и политической символики.

ЯЗЫК: всё три поля — по-русски. В headline и sub не используй кавычки и эмодзи.`;

export const VisualAgent = defineAgent({
  name: "visual",
  tier: "HAIKU",
  system: SYSTEM,
  inputSchema,
  outputSchema,
  maxOutputTokens: 700,
});

export type VisualInput = z.infer<typeof inputSchema>;
export type VisualOutput = z.infer<typeof outputSchema>;
