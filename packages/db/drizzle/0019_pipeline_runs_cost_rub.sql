-- Рублёвая себестоимость прогона (решение владельца 06.08.2026).
--
-- Тариф Timeweb AI Gateway объявлен В РУБЛЯХ, а таблица тарифов в коде считает
-- в долларах по зафиксированному курсу. Пока курс жил только в коде, рублёвая
-- сумма прошлого прогона менялась бы задним числом при каждой правке курса —
-- для счёта клиенту это недопустимо.
--
-- Поэтому рубли фиксируются В МОМЕНТ прогона, рядом с долларами. Доллары не
-- убираем: на них работает дневной потолок бюджета и весь существующий $-ledger.
--
-- NULL у исторических строк — честное «тогда не считали»; экраны пересчитают их
-- по текущему курсу и пометят это.
ALTER TABLE "pipeline_runs" ADD COLUMN IF NOT EXISTS "cost_rub" numeric(12, 4);
