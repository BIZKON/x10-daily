-- Баланс клиента, журнал движений и платежи (Спека 6, шаг 1).
--
-- Токены оплачиваем МЫ, клиент платит нам себестоимость ×3. До этой миграции
-- была только половина: рублёвая себестоимость прогона фиксировалась в
-- pipeline_runs.cost_rub, а получить с клиента деньги было нечем.
--
-- Шаг 1 намеренно НИЧЕГО не останавливает и ничего ни с кого не берёт: баланс
-- двигается, движения пишутся, но гейта по нулю нет (он — шаг 2), и пополнять
-- пока нечем (ЮKassa — шаги 3–4). Смысл шага: увидеть на живом потоке, сходится
-- ли расчёт с реальностью, ДО того как он начнёт останавливать конвейер.

-- Тип движения. `topup` — пополнение, `charge` — списание за прогон,
-- `adjust` — ручная правка (возврат, компенсация, исправление ошибки).
CREATE TYPE "balance_entry_kind" AS ENUM ('topup', 'charge', 'adjust');

-- Статусы платежа повторяют статусы ЮKassa: чужую модель здесь не выдумываем.
CREATE TYPE "payment_status" AS ENUM ('pending', 'succeeded', 'canceled');

-- ─────────────────────────────────────────────────────────────────────────────
-- Платежи
-- ─────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS "payments" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  -- id платежа в ЮKassa. NULL до ответа шлюза: строку создаём ПЕРЕД вызовом,
  -- чтобы её id пошёл в Idempotence-Key. UNIQUE держит одноразовость зачисления
  -- (ЮKassa повторяет уведомление, пока не получит 200, и не по одному разу).
  "provider_payment_id" varchar(64) UNIQUE,
  "amount_rub" numeric(14, 4) NOT NULL,
  "status" "payment_status" NOT NULL DEFAULT 'pending',
  -- Кто нажал «Пополнить». SET NULL: удаление сотрудника не должно стирать
  -- платёж — деньги пришли, и это факт бухгалтерии, а не свойство сотрудника.
  "created_by" uuid REFERENCES "users"("id") ON DELETE SET NULL,
  -- Почта плательщика: без неё касса не выбьет чек (54-ФЗ). Собирается на
  -- шаге 6; колонка заводится сразу, чтобы не мигрировать таблицу с деньгами.
  "payer_email" varchar(254),
  -- Момент зачисления на баланс. NULL = деньги ещё не зачислены.
  "credited_at" timestamptz,
  "created_at" timestamptz NOT NULL DEFAULT now(),
  "updated_at" timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS "payments_status_idx" ON "payments" ("status", "created_at" DESC);

-- ─────────────────────────────────────────────────────────────────────────────
-- Баланс экземпляра
-- ─────────────────────────────────────────────────────────────────────────────
--
-- Ровно одна строка на копию системы: `tenant_id` не вводим (решение 06.08.2026),
-- клиента отличает сам экземпляр. Синглтон держится типом ключа: id boolean
-- со значением true и CHECK — второй строки физически не появится, даже если
-- кто-то попробует вставить её руками.
CREATE TABLE IF NOT EXISTS "client_balance" (
  "id" boolean PRIMARY KEY DEFAULT true CHECK ("id"),
  "balance_rub" numeric(14, 4) NOT NULL DEFAULT 0,
  -- Ниже этого остатка предупреждаем (шаг 2). 500 ₽ — это примерно 12
  -- публикаций (≈42 ₽ за штуку по живому расходу прода 1–6.08.2026), то есть
  -- около трёх дней при ритме 4 поста в день. Запаса хватает, чтобы человек
  -- успел оплатить, и не настолько много, чтобы предупреждение стало фоном.
  "low_threshold_rub" numeric(14, 4) NOT NULL DEFAULT 500,
  -- Останавливать ли конвейер при нуле. Дефолт true — это правильное поведение
  -- для КЛИЕНТСКОЙ копии: неоплаченная работа не должна продолжаться.
  -- Для нашей собственной копии ниже выставляется false (мы платим сами себе).
  -- На шаге 1 флаг ещё никем не читается — он заводится заранее, чтобы шаг 2
  -- не остановил наш собственный завод в момент выкатки.
  "stop_on_zero" boolean NOT NULL DEFAULT true,
  "updated_at" timestamptz NOT NULL DEFAULT now()
);

-- ─────────────────────────────────────────────────────────────────────────────
-- Журнал движений
-- ─────────────────────────────────────────────────────────────────────────────
--
-- Отвечает на вопрос «почему остаток именно такой». Без журнала спор с клиентом
-- неразрешим: остаток — это одно число, а претензия всегда про конкретный день.
CREATE TABLE IF NOT EXISTS "balance_entries" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  "kind" "balance_entry_kind" NOT NULL,
  -- Со знаком: пополнение плюс, списание минус. Знак в самой сумме, а не в
  -- отдельной колонке, — тогда остаток это буквально sum(amount_rub), и
  -- расхождение с client_balance видно одним запросом.
  "amount_rub" numeric(14, 4) NOT NULL,
  -- Остаток ПОСЛЕ операции: чтобы показать историю, не пересчитывая её заново.
  "balance_after_rub" numeric(14, 4) NOT NULL,
  -- 🔴 SET NULL, а НЕ CASCADE. pipeline_runs удаляются каскадом вместе со
  -- статьёй; при CASCADE удаление статьи стирало бы и запись о деньгах.
  -- Финансовая история переживает удаление того, за что заплачено.
  "run_id" uuid REFERENCES "pipeline_runs"("id") ON DELETE SET NULL,
  "payment_id" uuid REFERENCES "payments"("id") ON DELETE SET NULL,
  -- Человеческое пояснение. Обязательно по смыслу для `adjust`: ручная правка
  -- без причины через месяц неотличима от ошибки.
  "note" text,
  "created_at" timestamptz NOT NULL DEFAULT now()
);

-- Один прогон — одно списание. Прямо сейчас повторно списать неоткуда (строка
-- pipeline_runs создаётся тем же вызовом), но инвариант должна держать база, а
-- не аккуратность вызывающего кода. NULL-ы в уникальном индексе не конфликтуют,
-- поэтому пополнения и правки индекс не трогает.
CREATE UNIQUE INDEX IF NOT EXISTS "balance_entries_run_uidx"
  ON "balance_entries" ("run_id") WHERE "kind" = 'charge';

CREATE INDEX IF NOT EXISTS "balance_entries_created_idx"
  ON "balance_entries" ("created_at" DESC);

-- ─────────────────────────────────────────────────────────────────────────────
-- Строка баланса этого экземпляра
-- ─────────────────────────────────────────────────────────────────────────────
--
-- stop_on_zero = false: это НАША копия, мы платим шлюзу напрямую и сами себе
-- ничего не переводим — остаток тут уйдёт в минус и должен уйти. Он показывает
-- накопленную стоимость нашего собственного контента в клиентских ценах, и
-- именно так проверяется, сходится ли расчёт. У клиента будет true.
INSERT INTO "client_balance" ("id", "balance_rub", "stop_on_zero")
VALUES (true, 0, false)
ON CONFLICT ("id") DO NOTHING;
