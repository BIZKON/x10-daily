-- Переименование client_balance.stop_on_zero → billing_enforced (Спека 6, шаг 2).
--
-- Флаг завели на шаге 1 как «останавливать ли конвейер при нуле». На шаге 2
-- выяснилось, что он управляет не только остановкой: у нашей собственной копии
-- баланс всегда отрицательный (мы платим шлюзу напрямую и сами себе не
-- переводим), и с прежним смыслом она каждый день получала бы предупреждение
-- «деньги кончились». Ложная тревога раз в сутки — это способ научить людей
-- не читать тревоги.
--
-- Поэтому флаг теперь честно называется «включён ли денежный контур в этой
-- копии» и гасит И остановку, И предупреждения разом.
--
-- Безопасно: колонку пока никто не читает — она заведена час назад тем же
-- шагом 1 и ни в одном запросе не участвует.
ALTER TABLE "client_balance" RENAME COLUMN "stop_on_zero" TO "billing_enforced";

COMMENT ON COLUMN "client_balance"."billing_enforced" IS
  'Включён ли денежный контур в этой копии: остановка по нулю + предупреждения. У клиента true, у нашей копии false.';
