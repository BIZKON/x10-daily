-- Виды алертов про баланс клиента (Спека 6, шаг 2).
--
-- Переиспользуем cost_alerts, а не заводим свою таблицу: там уже есть ровно то,
-- что нужно деньгам — идемпотентность «один алерт на (день, вид)» и очередь
-- дослыки (retry-ops-alerts). Предупреждение о деньгах, потерянное из-за
-- хиккапа сети, — это ровно тот случай, ради которого дослыку и строили.
--
-- 🔴 ОТДЕЛЬНЫЙ ФАЙЛ миграции. PostgreSQL запрещает использовать новое значение
-- enum в той же транзакции, где оно добавлено (CLAUDE.md §8). Здесь только
-- ADD VALUE; писать этими значениями будет рантайм — другая транзакция.
--
-- `balance_low` — остаток ниже порога, конвейер ещё работает.
-- `balance_empty` — остаток исчерпан, новая работа не берётся.
ALTER TYPE "cost_alert_kind" ADD VALUE IF NOT EXISTS 'balance_low';
ALTER TYPE "cost_alert_kind" ADD VALUE IF NOT EXISTS 'balance_empty';
