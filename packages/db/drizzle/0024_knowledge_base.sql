-- База знаний клиента (обещание КП от 10.08.2026, реестр разрыва §3.1).
--
-- Зачем: без неё раздел «Создать» — обычный чат, то есть ровно то возражение,
-- которое коммерческое предложение обещает закрыть целым разделом. Знание о
-- бизнесе должно жить в системе, а не в каждом запросе человека.
--
-- 🔴 Векторного поиска здесь НЕТ, и это осознанно. Таблица `article_embeddings`
-- заведена ещё в X10-эпоху, но кода к ней нет ни строки — эмбеддингов в
-- проекте не существует, а их появление упирается в отдельный вопрос: отдаёт
-- ли шлюз embeddings-модель. При этом база знаний клиента МАЛА: прайс, список
-- продуктов и частые возражения — это тысячи токенов, а не миллионы. Полки
-- дают структуру, нужную полку кладём в промпт целиком. Вектора понадобятся,
-- когда корпус перестанет влезать в окно; тогда это будет отдельная миграция и
-- отдельное решение, а не догадка авансом.

-- ── Полки ────────────────────────────────────────────────────────────────
-- Смысловые разделы знания, а не папки файлов. Экран показывает наполненность
-- каждой: пустая полка «Возражения» видна сразу, и клиент понимает, чего не
-- хватает, без нашей подсказки.
--
-- Набор полок — КОНФИГУРАЦИЯ ЭКЗЕМПЛЯРА, а не константа кода: у стоматологии и
-- у логистики разные полки. Ниже засеян стартовый набор, клиент правит его сам.
CREATE TABLE IF NOT EXISTS "kb_shelves" (
  "id"          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  "slug"        varchar(48)  NOT NULL,
  "title"       varchar(120) NOT NULL,
  -- «Зачем эта полка» по-русски. Канон админки: у каждого поля есть
  -- раскрывающееся объяснение, потому что клиент не читает наши доки и не
  -- может спросить разработчика.
  "purpose"     text         NOT NULL,
  -- Вопрос для режима анкеты: пока полки пусты, экран спрашивает, а не молчит
  -- пустой формой загрузки.
  "question"    text         NOT NULL,
  "hint"        text,
  "position"    integer      NOT NULL DEFAULT 0,
  -- Обязательная полка попадает в анкету и считается в прогрессе заполнения.
  "required"    boolean      NOT NULL DEFAULT true,
  "enabled"     boolean      NOT NULL DEFAULT true,
  "created_at"  timestamptz  NOT NULL DEFAULT now(),
  "updated_at"  timestamptz  NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS "kb_shelves_slug_uidx" ON "kb_shelves" ("slug");
CREATE INDEX IF NOT EXISTS "kb_shelves_order_idx" ON "kb_shelves" ("enabled", "position");

-- ── Материалы ────────────────────────────────────────────────────────────
-- 🔴 Ответ на вопрос анкеты и загруженный файл — ОДНА сущность.
-- Разводить их по двум таблицам значило бы держать два хранилища одного и того
-- же знания и дважды писать выборку для промпта. Отличаются они полем `source`.
CREATE TABLE IF NOT EXISTS "kb_documents" (
  "id"            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  -- RESTRICT, а не CASCADE: удаление полки не должно молча уносить знание.
  -- Сначала перенеси материалы, потом убирай полку.
  "shelf_id"      uuid NOT NULL REFERENCES "kb_shelves"("id") ON DELETE RESTRICT,
  "title"         varchar(240) NOT NULL,
  -- answer — ответ человека в анкете; file — извлечённый текст загруженного
  -- документа; url — страница по адресу.
  "source"        varchar(16)  NOT NULL DEFAULT 'answer',
  -- Текст, который реально уедет в промпт. Для answer это сам ответ.
  "body"          text         NOT NULL,
  "file_name"     varchar(240),
  "file_bytes"    integer,
  "source_url"    text,
  -- ready — можно использовать; parsing — файл разбирается; failed — из файла
  -- не достали текста (скан без распознавания и подобное).
  "status"        varchar(16)  NOT NULL DEFAULT 'ready',
  "status_reason" text,
  "char_count"    integer      NOT NULL DEFAULT 0,
  "created_by"    uuid REFERENCES "users"("id") ON DELETE SET NULL,
  "created_at"    timestamptz  NOT NULL DEFAULT now(),
  "updated_at"    timestamptz  NOT NULL DEFAULT now()
);

-- varchar + CHECK, а не pg enum: набор состояний ещё будет меняться, когда
-- появится разбор файлов, а из enum значение не выкинуть (CLAUDE.md §8).
ALTER TABLE "kb_documents" DROP CONSTRAINT IF EXISTS "kb_documents_source_chk";
ALTER TABLE "kb_documents" ADD CONSTRAINT "kb_documents_source_chk"
  CHECK ("source" IN ('answer', 'file', 'url'));

ALTER TABLE "kb_documents" DROP CONSTRAINT IF EXISTS "kb_documents_status_chk";
ALTER TABLE "kb_documents" ADD CONSTRAINT "kb_documents_status_chk"
  CHECK ("status" IN ('ready', 'parsing', 'failed'));

-- Основная выборка — «материалы полки, свежие сверху».
CREATE INDEX IF NOT EXISTS "kb_documents_shelf_idx"
  ON "kb_documents" ("shelf_id", "created_at" DESC);
-- Выборка для промпта берёт только готовое.
CREATE INDEX IF NOT EXISTS "kb_documents_ready_idx"
  ON "kb_documents" ("status", "shelf_id");

