-- База знаний по ссылке: состояние «предложено» (спека 11.08, §6).
--
-- Клиент даёт адрес сайта, система обходит страницы и раскладывает найденное по
-- полкам. Найденное НЕ становится знанием молча — оно ждёт человека.
--
-- 🔴 Почему это безопасно по умолчанию, а не по дисциплине: `loadKnowledge`
-- выбирает только `status = 'ready'` (apps/workers/pipeline/src/lib/knowledge.ts).
-- Значит непринятое предложение физически не может уехать в промпт агента, даже
-- если про него забыли на месяц. Безопасность держится на условии, которое уже
-- написано и уже работает, а не на новом правиле, которое надо помнить.
--
-- Расширение дешёвое ровно потому, что автор 0024 выбрал varchar + CHECK, а не
-- pg enum, и прямо написал почему: набор состояний ещё будет меняться.

ALTER TABLE "kb_documents" DROP CONSTRAINT IF EXISTS "kb_documents_status_chk";
ALTER TABLE "kb_documents" ADD CONSTRAINT "kb_documents_status_chk"
  CHECK ("status" IN ('ready', 'parsing', 'failed', 'proposed'));
